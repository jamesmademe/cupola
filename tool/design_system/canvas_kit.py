#!/usr/bin/env python3
"""Writes the canvas kit: the design tokens as the mockup canvas's boards use them.

The boards of the Cupola mockup canvas are HTML; without a kit they spell
their colours, sizes and type by hand and drift from the app. The kit is
generated from design/system/tokens.json, never edited:

    python3 tool/design_system/canvas_kit.py --out .ai/scratch/canvas-kit \\
        [--services-font-url /_blob/<id>]

writes, under <out>/project/kit/ (the canvas's own path for it):

- tokens.css: the custom properties per theme (`:root, [data-theme="dark"]`
  and `[data-theme="light"]`), the shared ones, and a `.t-<role>` class per
  text role. A board links it right after its `support.js` line:
  `<link rel="stylesheet" href="kit/tokens.css">`.
- kit.json: the sha256 of the tokens.json it was made from, so a board's kit
  can be told stale, and the Google Fonts line a board's `<helmet>` carries
  (the canvas allows no other network, so the stylesheet imports nothing).

The CupolaServices face is not on Google Fonts: upload the .otf to the canvas
as an asset and pass the address it is given; without one the kit has no
@font-face for it.

Publish both files to the canvas from <out>, and check a board with
lint_boards.py before publishing it.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

from tokens_css import tokens_css, type_css

ROOT = Path(__file__).resolve().parents[2]
TOKENS = ROOT / "design" / "system" / "tokens.json"
KIT = Path("project") / "kit"

GOOGLE_FONTS = (
    "https://fonts.googleapis.com/css2?"
    "family=Bricolage+Grotesque:opsz,wdth,wght@12..96,75..100,200..800"
    "&family=Onest:wght@100..900"
    "&family=Geist+Mono:wght@100..900"
    "&display=swap"
)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--out", type=Path, required=True, help="the folder that holds project/")
    parser.add_argument("--services-font-url", help="the canvas asset address of CupolaServices.otf")
    args = parser.parse_args(argv)

    source = TOKENS.read_bytes()
    tokens = json.loads(source)

    def font_url(font: dict) -> str | None:
        return args.services_font_url if font["family"] == "CupolaServices" else None

    kit = args.out / KIT
    kit.mkdir(parents=True, exist_ok=True)
    header = (
        "/* Generated by tool/design_system/canvas_kit.py from "
        "design/system/tokens.json. Never edit: regenerate. */"
    )
    (kit / "tokens.css").write_text(
        f"{header}\n{tokens_css(tokens, font_url)}\n{type_css(tokens)}\n"
    )
    (kit / "kit.json").write_text(json.dumps({
        "generatedBy": "tool/design_system/canvas_kit.py",
        "tokens": "design/system/tokens.json",
        "tokensSha256": hashlib.sha256(source).hexdigest(),
        "version": tokens.get("version"),
        "fontsLink": GOOGLE_FONTS,
        "servicesFont": args.services_font_url,
    }, indent=2) + "\n")
    print(kit / "tokens.css")
    print(kit / "kit.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
