/// The widgets' colours and type are the app's, read from the live theme.
///
/// A widget cannot run Dart, and what the app paints is not in the token JSON
/// alone: each tone is walked for contrast against its ground at run time
/// (`statusToneColor`), and the roles are built from variable-font axes by
/// `AppTheme`. So this test builds both rooms, renders what the extension
/// needs as `OutsideStyle.swift` and what Android's widgets need as resources
/// (`outside_style.xml`: the colours of each room, where Android resolves
/// light and dark by directory, and the type roles and sizes, which are the
/// same in both), and fails when a file is not what the theme says. A change
/// to a token, a tone or a role cannot reach the app without reaching the
/// widgets: regenerate with
///
///     UPDATE_NATIVE_STYLE=1 flutter test test/features/outside/native_style_test.dart
const _swiftPath = 'ios/CupolaWidgets/OutsideStyle.swift';
const _androidLightPath = 'android/app/src/main/res/values/outside_style.xml';
const _androidNightPath =
    'android/app/src/main/res/values-night/outside_style.xml';
const _testPath = 'test/features/outside/native_style_test.dart';
const _generated = 'Generated by $_testPath. Do not edit.';
const _regenerate = 'UPDATE_NATIVE_STYLE=1 flutter test $_testPath';

/// A scrim over artwork is the same in both rooms: the picture is dark or
/// light whatever room the phone is in, so the words over it never follow the
/// room. These are the approved board's own bytes (T3 board: `_onArt`,
/// `_onArtDim`, and the `0A0A0D` foot of `_ArtPlate`). The scrim is the dark
/// room's own ground, so a tone over it is the dark room's tone, already
/// walked for that ground (asserted below).
const _onArt = Color(0xFFF7F6F2);
const _onArtDim = Color(0xB8FFFFFF);
const _scrimClear = Color(0x000A0A0D);
const _scrimFoot = Color(0xE60A0A0D);

/// One type role as the native side needs it: everything `UIFontDescriptor`
/// takes, and the line and tracking a `Text` takes.
typedef _Role = ({
  String family,
  double size,
  double lineHeight,
  double tracking,
  List<(String, double)> axes,
  bool tabular,
});

typedef _Room = ({
  Color ground,
  Color ink,
  Color dim,
  Color track,
  Color green,
  Color amber,
  Color blue,
  Color neutral,
});

_Role _roleOf(TextStyle style) {
  final variations = <String, double>{
    for (final variation in style.fontVariations ?? const <FontVariation>[])
      variation.axis: variation.value,
  };
  // The axes the faces have, in a fixed order, then anything else a role may
  // one day name: an axis that is dropped here is a drawing that drifts.
  const known = ['wght', 'wdth', 'opsz'];
  final axes = <(String, double)>[
    for (final tag in known)
      if (variations[tag] != null) (tag, variations[tag]!),
    for (final tag in (variations.keys.toList()..sort()))
      if (!known.contains(tag)) (tag, variations[tag]!),
  ];
  expect(variations['wght'], isNotNull, reason: 'a role names its weight axis');
  return (
    family: style.fontFamily!,
    size: style.fontSize!,
    lineHeight: style.height!,
    tracking: style.letterSpacing ?? 0,
    axes: axes,
    tabular:
        style.fontFeatures?.any(
          (feature) => feature.feature == 'tnum' && feature.value == 1,
        ) ??
        false,
  );
}

Map<String, _Role> _rolesOf(ThemeData theme) {
  final text = theme.textTheme;
  return {
    'label': _roleOf(text.labelMedium!),
    'title': _roleOf(text.titleSmall!.weight(FontWeight.w600)),
    'line': _roleOf(text.bodySmall!),
    'data': _roleOf(AppTheme.data(theme.brightness)),
    'figureHero': _roleOf(AppType.figureHero),
    'figureSmall': _roleOf(AppType.figureSmall),
  };
}

_Room _roomOf(ThemeData theme) {
  final scheme = theme.colorScheme;
  final ground = scheme.surface;
  return (
    ground: ground,
    ink: scheme.onSurface,
    dim: theme.extension<CupolaThemeColors>()!.dimText,
    track: scheme.onSurface.withValues(alpha: 0.12),
    green: statusToneColor(scheme, StatusTone.success, surface: ground),
    amber: statusToneColor(scheme, StatusTone.warning, surface: ground),
    blue: statusToneColor(scheme, StatusTone.info, surface: ground),
    neutral: statusToneColor(scheme, StatusTone.neutral),
  );
}

String _number(double value) {
  if (value == value.roundToDouble()) return value.toInt().toString();
  final fixed = value.toStringAsFixed(4);
  final trimmed = fixed.replaceFirst(RegExp(r'0+$'), '');
  return trimmed.endsWith('.')
      ? trimmed.substring(0, trimmed.length - 1)
      : trimmed;
}

String _byte(double channel) => (channel * 255).round().toString();

String _color(Color color) =>
    'Color(.sRGB, red: ${_byte(color.r)} / 255, green: ${_byte(color.g)} / 255, '
    'blue: ${_byte(color.b)} / 255, opacity: ${_number(color.a)})';

String _roomSource(String name, _Room room) {
  final fields = <String, Color>{
    'ground': room.ground,
    'ink': room.ink,
    'dim': room.dim,
    'track': room.track,
    'green': room.green,
    'amber': room.amber,
    'blue': room.blue,
    'neutral': room.neutral,
  };
  return [
    '  static let $name = OutsideRoom(',
    for (final MapEntry(:key, :value) in fields.entries)
      '    $key: ${_color(value)},',
    '  )',
  ].join('\n');
}

String _roleSource(String name, _Role role) {
  final axes = role.axes
      .map((axis) => 'OutsideAxis("${axis.$1}", ${_number(axis.$2)})')
      .join(', ');
  return [
    '  static let $name = OutsideRole(',
    '    family: "${role.family}",',
    '    size: ${_number(role.size)},',
    '    lineHeight: ${_number(role.lineHeight)},',
    '    tracking: ${_number(role.tracking)},',
    '    axes: [$axes],',
    '    tabular: ${role.tabular}',
    '  )',
  ].join('\n');
}

/// `OutsideStyle.swift` as the live theme says it.
String renderNativeStyle() {
  final dark = AppTheme.darkTheme();
  final light = AppTheme.lightTheme();
  final darkRoles = _rolesOf(dark);
  final lightRoles = _rolesOf(light);
  // One drawing in both rooms: only colour follows the room, so the roles are
  // emitted once, and a role that ever differs between rooms must be a
  // decision of this test, not a silent pick of one.
  for (final name in darkRoles.keys) {
    expect(
      _roleSource(name, lightRoles[name]!),
      _roleSource(name, darkRoles[name]!),
      reason: 'the "$name" role differs between the rooms',
    );
  }
  final darkRoom = _roomOf(dark);
  final lightRoom = _roomOf(light);
  expect(
    darkRoom.ground,
    _scrimFoot.withValues(alpha: 1),
    reason: 'the scrim is the dark ground: a tone over it is the dark tone',
  );
  for (final (room, colors) in [('dark', darkRoom), ('light', lightRoom)]) {
    for (final color in [
      colors.ground,
      colors.ink,
      colors.dim,
      colors.green,
      colors.amber,
      colors.blue,
      colors.neutral,
    ]) {
      expect(color.a, 1.0, reason: 'a $room colour is opaque');
    }
  }

  final b = StringBuffer()
    ..writeln(
      '// Generated by test/features/outside/native_style_test.dart. Do not edit.',
    )
    ..writeln('// Regenerate: UPDATE_NATIVE_STYLE=1 flutter test $_testPath')
    ..writeln()
    ..writeln('import SwiftUI')
    ..writeln()
    ..writeln('/// The colours of each room, as the app paints them: the tones')
    ..writeln(
      '/// are already walked for contrast against that room\'s ground.',
    )
    ..writeln('extension OutsideRoom {')
    ..writeln(_roomSource('dark', darkRoom))
    ..writeln()
    ..writeln(_roomSource('light', lightRoom))
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// The type roles the widgets draw with. The same in both rooms:',
    )
    ..writeln('/// only colour follows the room.')
    ..writeln('extension OutsideRole {');
  final roles = darkRoles.entries.toList();
  for (var i = 0; i < roles.length; i++) {
    b.writeln(_roleSource(roles[i].key, roles[i].value));
    if (i != roles.length - 1) b.writeln();
  }
  b
    ..writeln('}')
    ..writeln()
    ..writeln('enum OutsideStyle {')
    ..writeln(
      '  /// Words over artwork, and the scrim that darkens its foot. The',
    )
    ..writeln(
      '  /// same in both rooms: a picture is dark or light whatever room the',
    )
    ..writeln(
      '  /// phone is in, so the words over it never follow the room. A tone',
    )
    ..writeln(
      '  /// over the scrim is the dark room\'s: the scrim is its ground.',
    )
    ..writeln('  static let onArt = ${_color(_onArt)}')
    ..writeln('  static let onArtDim = ${_color(_onArtDim)}')
    ..writeln('  static let scrimClear = ${_color(_scrimClear)}')
    ..writeln('  static let scrimFoot = ${_color(_scrimFoot)}')
    ..writeln()
    ..writeln(
      '  static let posterRadius: CGFloat = ${_number(AppRadius.poster)}',
    )
    ..writeln(
      '  static let tinyPosterRadius: CGFloat = ${_number(AppRadius.xs)}',
    )
    ..writeln()
    ..writeln('  static let spaceXxs: CGFloat = ${_number(AppSpacing.xxs)}')
    ..writeln('  static let spaceXs: CGFloat = ${_number(AppSpacing.xs)}')
    ..writeln('  static let spaceS: CGFloat = ${_number(AppSpacing.s)}')
    ..writeln('  static let spaceSm: CGFloat = ${_number(AppSpacing.sm)}')
    ..writeln('  static let spaceRow: CGFloat = ${_number(AppSpacing.row)}')
    ..writeln('  static let spaceSlabY: CGFloat = ${_number(AppSpacing.slabY)}')
    ..writeln('}');
  return b.toString();
}

// Android -------------------------------------------------------------------

/// `#AARRGGBB`, the way an Android colour resource spells it.
String _argb(Color color) =>
    '#${color.toARGB32().toRadixString(16).padLeft(8, '0').toUpperCase()}';

/// A room's colours as `outside_*` colour resources. The ones that are the
/// same in both rooms (words over artwork, the scrim, and the tones over it)
/// are in both files, so that each room's file is complete on its own.
///
/// The tones over artwork are the dark room's, since the scrim is its ground:
/// not a colour a layout can take from its room.
List<String> _androidColors(_Room room, _Room dark) {
  final colors = <String, Color>{
    'ground': room.ground,
    'ink': room.ink,
    'dim': room.dim,
    'track': room.track,
    'green': room.green,
    'amber': room.amber,
    'blue': room.blue,
    'neutral': room.neutral,
    'on_art': _onArt,
    'on_art_dim': _onArtDim,
    'art_green': dark.green,
    'art_amber': dark.amber,
    'art_blue': dark.blue,
    'art_neutral': dark.neutral,
    'scrim_clear': _scrimClear,
    'scrim_foot': _scrimFoot,
  };
  return [
    for (final MapEntry(:key, :value) in colors.entries)
      '    <color name="outside_$key">${_argb(value)}</color>',
  ];
}

List<String> _androidHeader(String room) => [
  '<?xml version="1.0" encoding="utf-8"?>',
  '<!-- $_generated -->',
  '<!-- Regenerate: $_regenerate -->',
  '<!-- The $room room. Android resolves it by directory, and the launcher',
  '     that draws a widget picks the directory from its own night mode. -->',
];

/// A line's height in sp: Flutter's `height` is a multiple of the size, and
/// `android:lineHeight` is the line itself. Two decimals: `1.3846 * 13` is
/// 17.9998, and the role means 18.
String _lineHeight(_Role role) =>
    _number((role.size * role.lineHeight * 100).round() / 100);

/// Flutter's tracking is in logical pixels at the role's size, Android's in
/// em.
String _letterSpacing(_Role role) => _number(role.tracking / role.size);

/// A `res/font/` name: the family, lowercased (`android/app/build.gradle.kts`
/// copies the app's font files there under these names).
String _fontResource(String family) =>
    family.toLowerCase().replaceAll(' ', '_');

/// The role's weight, which a launcher that cannot load its face still takes.
String _weight(_Role role) =>
    _number(role.axes.firstWhere((axis) => axis.$1 == 'wght').$2);

List<String> _androidStyle(String name, _Role role) {
  final axes = role.axes
      .map((axis) => "'${axis.$1}' ${_number(axis.$2)}")
      .join(', ');
  final style = '${name[0].toUpperCase()}${name.substring(1)}';
  return [
    '    <style name="OutsideText.$style" tools:targetApi="28">',
    '        <item name="android:fontFamily">@font/${_fontResource(role.family)}</item>',
    '        <item name="android:textSize">${_number(role.size)}sp</item>',
    '        <item name="android:letterSpacing">${_letterSpacing(role)}</item>',
    '        <item name="android:fontVariationSettings">"$axes"</item>',
    '        <item name="android:textFontWeight">${_weight(role)}</item>',
    if (role.tabular)
      '        <item name="android:fontFeatureSettings">"tnum"</item>',
    '        <item name="android:lineHeight">${_lineHeight(role)}sp</item>',
    '    </style>',
  ];
}

String _androidDimen(String name, double value) =>
    '    <dimen name="outside_$name">${_number(value)}dp</dimen>';

/// The files Android reads, by path: the light room's colours with the type
/// roles and sizes, and the dark room's colours. The roles are the same in
/// both rooms (`renderNativeStyle` asserts it), so they are emitted once, in
/// `values/`, and `values-night/` inherits them.
Map<String, String> renderAndroidStyle() {
  final dark = AppTheme.darkTheme();
  final light = AppTheme.lightTheme();
  final darkRoom = _roomOf(dark);
  final lightRoom = _roomOf(light);
  final roles = _rolesOf(dark);
  return {
    _androidLightPath: [
      ..._androidHeader('light'),
      '<resources xmlns:tools="http://schemas.android.com/tools">',
      ..._androidColors(lightRoom, darkRoom),
      '',
      '    <!-- The type roles the widgets draw with, as the app builds them.',
      '         A launcher inflates a widget with a restricted context, which',
      '         does not load a font from the app\'s resources: `fontFamily`',
      '         falls back to the system face there, and what still reaches it',
      '         is the weight (`textFontWeight`, and every axis of',
      '         `fontVariationSettings` that the system face has). So the faces',
      '         named here are the ones the app draws with in its own process,',
      '         where `OutsideFigure` uses them for the figure that leads a',
      '         small widget, drawn into a bitmap; the rest of a widget is the',
      '         system face at the role\'s weight, size, tracking and line.',
      '         `res/font/` is copied from `assets/fonts/` by the build.',
      '         Those three attributes and `lineHeight` are Android 9 (28): below',
      '         it a widget is in the system face at its regular weight and its',
      '         own line, legible and only less exact, never missing. -->',
      '    <style name="OutsideText" tools:targetApi="28">',
      '        <!-- The role\'s own line is the line. -->',
      '        <item name="android:includeFontPadding">false</item>',
      '    </style>',
      for (final MapEntry(:key, :value) in roles.entries)
        ..._androidStyle(key, value),
      '',
      _androidDimen('poster_radius', AppRadius.poster),
      _androidDimen('tiny_poster_radius', AppRadius.xs),
      _androidDimen('space_xxs', AppSpacing.xxs),
      _androidDimen('space_xs', AppSpacing.xs),
      _androidDimen('space_s', AppSpacing.s),
      _androidDimen('space_sm', AppSpacing.sm),
      _androidDimen('space_row', AppSpacing.row),
      _androidDimen('space_slab_y', AppSpacing.slabY),
      '</resources>',
      '',
    ].join('\n'),
    _androidNightPath: [
      ..._androidHeader('dark'),
      '<resources>',
      ..._androidColors(darkRoom, darkRoom),
      '</resources>',
      '',
    ].join('\n'),
  };
}

/// Every file the widgets take from the theme, by path.
Map<String, String> renderAll() => {
  _swiftPath: renderNativeStyle(),
  ...renderAndroidStyle(),
};

void main() {
  test('the files the widgets take from the theme are what it paints', () {
    final rendered = renderAll();
    if (Platform.environment['UPDATE_NATIVE_STYLE'] == '1') {
      for (final MapEntry(:key, :value) in rendered.entries) {
        File(key)
          ..parent.createSync(recursive: true)
          ..writeAsStringSync(value);
      }
      return;
    }
    final stale = [
      for (final MapEntry(:key, :value) in rendered.entries)
        if (!File(key).existsSync() || File(key).readAsStringSync() != value)
          key,
    ];
    if (stale.isNotEmpty) {
      fail(
        '${stale.join(', ')} ${stale.length == 1 ? 'is' : 'are'} missing or '
        'not what the theme paints. A token, a tone or a type role changed: '
        'regenerate with\n'
        '  $_regenerate',
      );
    }
  });

  test('each file asks to be regenerated, not edited', () {
    final rendered = renderAll();
    expect(
      rendered[_swiftPath]!.split('\n').first,
      '// Generated by $_testPath. Do not edit.',
    );
    for (final path in [_androidLightPath, _androidNightPath]) {
      expect(
        rendered[path]!.split('\n')[1],
        '<!-- Generated by $_testPath. Do not edit. -->',
      );
    }
  });

  test('no em dash reaches the widgets', () {
    for (final MapEntry(:key, :value) in renderAll().entries) {
      expect(value, isNot(contains(String.fromCharCode(0x2014))), reason: key);
    }
  });

  test('Android names the same roles as the Swift file', () {
    // The three drawings are one drawing: a role in one file and not the
    // other is a size that drifts.
    final swift = RegExp(
      r'static let (\w+) = OutsideRole',
    ).allMatches(renderNativeStyle()).map((match) => match.group(1)!).toSet();
    final android = RegExp(r'<style name="OutsideText\.(\w+)"')
        .allMatches(renderAndroidStyle()[_androidLightPath]!)
        .map((match) {
          final name = match.group(1)!;
          return '${name[0].toLowerCase()}${name.substring(1)}';
        })
        .toSet();
    expect(android, swift);
  });
}
